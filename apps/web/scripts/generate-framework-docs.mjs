#!/usr/bin/env node
// Generates the per-framework docs trees under content/docs/{nextjs,react,core} from the
// shared bodies in content/shared.
//
// One body, written once, is published under every framework it applies to. Each
// published page is a thin wrapper — frontmatter plus an <include> of the body — so the
// three copies of a page can never drift, and adding a page to a framework is one
// frontmatter entry. The build-time plugin (src/lib/remark-framework-docs.ts) then
// resolves <Framework when="…"> blocks and the package name for the framework the
// wrapper sits under.
//
// A body opts in with `frameworks:` in its frontmatter — explicitly, so that publishing a
// React-only page to JavaScript is a decision someone made, not a default they forgot.
//
// Output is committed, and regenerated by `pnpm dev` and `pnpm build`, the same way the
// changelog pages are. The framework directories are wholly owned by this script:
// anything hand-placed in them is removed on the next run.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const sharedDir = join(webRoot, "content", "shared");
const docsDir = join(webRoot, "content", "docs");

/** Sidebar root title per framework, in the order the switcher lists them. */
const FRAMEWORKS = {
  nextjs: "Next.js",
  react: "React",
  core: "JavaScript",
};

/** Section (and root-level page) order for every framework's sidebar. */
const rootOrder = JSON.parse(readFileSync(join(sharedDir, "_root-order.json"), "utf8")).pages;

// ---------------------------------------------------------------------------------------
// Frontmatter. The bodies use a small, fixed set of keys, so a strict reader is enough and
// keeps the script dependency-free. Anything it cannot read is an error, never a guess.
// ---------------------------------------------------------------------------------------

const KNOWN_KEYS = new Set(["title", "description", "frameworks", "full"]);

function unquote(value) {
  const v = value.trim();
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
    return v.slice(1, -1);
  }
  return v;
}

function readFrontmatter(source, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(source);
  if (!match) throw new Error(`${file}: missing frontmatter`);

  const data = {};
  for (const raw of match[1].split(/\r?\n/)) {
    if (!raw.trim()) continue;
    const idx = raw.indexOf(":");
    if (idx === -1) throw new Error(`${file}: cannot read frontmatter line ${JSON.stringify(raw)}`);
    const key = raw.slice(0, idx).trim();
    const value = raw.slice(idx + 1).trim();
    if (!KNOWN_KEYS.has(key)) throw new Error(`${file}: unknown frontmatter key "${key}"`);

    if (key === "frameworks") {
      const inner = /^\[(.*)\]$/.exec(value);
      if (!inner) throw new Error(`${file}: frameworks must be written as [nextjs, react, core]`);
      data.frameworks = inner[1]
        .split(",")
        .map((s) => unquote(s))
        .filter(Boolean);
      for (const fw of data.frameworks) {
        if (!(fw in FRAMEWORKS)) throw new Error(`${file}: unknown framework "${fw}"`);
      }
    } else if (key === "full") {
      data.full = value === "true";
    } else {
      data[key] = unquote(value);
    }
  }

  if (!data.title) throw new Error(`${file}: frontmatter needs a title`);
  if (!data.frameworks?.length) {
    throw new Error(
      `${file}: frontmatter needs frameworks: [...] naming every framework it is published under`,
    );
  }
  return { data, body: source.slice(match[0].length) };
}

// ---------------------------------------------------------------------------------------
// Collection
// ---------------------------------------------------------------------------------------

/** Every shared body, as { rel: "hooks/use-consent", data }. Underscore files are private. */
function collectBodies(dir = sharedDir, prefix = "") {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (entry.name.startsWith("_")) continue;
    const abs = join(dir, entry.name);
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      out.push(...collectBodies(abs, rel));
    } else if (entry.name.endsWith(".mdx")) {
      const { data } = readFrontmatter(readFileSync(abs, "utf8"), rel);
      out.push({ rel: rel.slice(0, -".mdx".length), abs, data });
    }
  }
  return out;
}

// ---------------------------------------------------------------------------------------
// Writers
// ---------------------------------------------------------------------------------------

function yamlString(value) {
  return JSON.stringify(value);
}

function writeWrapper(framework, body) {
  const outFile = join(docsDir, framework, `${body.rel}.mdx`);
  mkdirSync(dirname(outFile), { recursive: true });

  const includePath = relative(dirname(outFile), body.abs).split(sep).join("/");
  const lines = ["---", `title: ${yamlString(body.data.title)}`];
  if (body.data.description) lines.push(`description: ${yamlString(body.data.description)}`);
  if (body.data.full) lines.push("full: true");
  lines.push(
    "---",
    "",
    `{/* Generated by scripts/generate-framework-docs.mjs from content/shared/${body.rel}.mdx. Edit that file, not this one. */}`,
    "",
    `<include>${includePath}</include>`,
    "",
  );
  writeFileSync(outFile, lines.join("\n"));
}

/**
 * A section's meta.json for one framework: the shared meta.json with `pages` reduced to
 * what exists under that framework. Separators ("--- Label ---") are kept only when a
 * page follows them.
 */
function writeSectionMeta(framework, section, present) {
  const sharedMeta = join(sharedDir, section, "meta.json");
  if (!existsSync(sharedMeta)) return false;
  const meta = JSON.parse(readFileSync(sharedMeta, "utf8"));

  const pages = [];
  let pendingSeparator = null;
  for (const entry of meta.pages ?? []) {
    if (/^---.*---$/.test(entry)) {
      pendingSeparator = entry;
      continue;
    }
    if (!present.has(`${section}/${entry}`)) continue;
    if (pendingSeparator) pages.push(pendingSeparator);
    pendingSeparator = null;
    pages.push(entry);
  }
  if (pages.length === 0) return false;

  const outFile = join(docsDir, framework, section, "meta.json");
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, `${JSON.stringify({ ...meta, pages }, null, 2)}\n`);
  return true;
}

function writeRootMeta(framework, sectionsPresent, pagesPresent) {
  const pages = [];
  for (const entry of rootOrder) {
    if (sectionsPresent.has(entry) || pagesPresent.has(entry)) pages.push(entry);
  }
  const meta = { title: FRAMEWORKS[framework], root: true, pages };
  writeFileSync(join(docsDir, framework, "meta.json"), `${JSON.stringify(meta, null, 2)}\n`);
}

// ---------------------------------------------------------------------------------------

function main() {
  const bodies = collectBodies();
  const counts = {};

  for (const framework of Object.keys(FRAMEWORKS)) {
    rmSync(join(docsDir, framework), { recursive: true, force: true });

    const mine = bodies.filter((b) => b.data.frameworks.includes(framework));
    const present = new Set(mine.map((b) => b.rel));
    const sections = new Set(
      mine.filter((b) => b.rel.includes("/")).map((b) => b.rel.split("/")[0]),
    );
    const rootPages = new Set(mine.filter((b) => !b.rel.includes("/")).map((b) => b.rel));

    for (const body of mine) writeWrapper(framework, body);
    const sectionsWritten = new Set();
    for (const section of sections) {
      if (writeSectionMeta(framework, section, present)) sectionsWritten.add(section);
    }
    writeRootMeta(framework, sectionsWritten, rootPages);
    counts[framework] = mine.length;
  }

  writeFileSync(
    join(docsDir, "meta.json"),
    `${JSON.stringify({ title: "SDKs", pages: [...Object.keys(FRAMEWORKS), "changelog"] }, null, 2)}\n`,
  );

  console.log(
    `[generate-framework-docs] ${bodies.length} shared bodies → ` +
      Object.entries(counts)
        .map(([fw, n]) => `${fw}: ${n} pages`)
        .join(", "),
  );
}

main();

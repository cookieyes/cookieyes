#!/usr/bin/env node
// Reads `matrix/matrix-results.json` (produced by the DEVP-80 CI peer-dependency matrix) and
// `matrix/matrix.config.mjs` (the latter only to know which combination IDs *should* be present),
// then writes `apps/web/.generated/peer-matrix-reference.json` and injects marker-delimited
// markdown compatibility tables into `README.md`, `sdk/react/README.md`, `sdk/nextjs/README.md`.
//
// Sibling to `generate-config-reference.mjs` / `generate-component-reference.mjs` /
// `generate-css-variables-reference.mjs` — same fail-closed discipline, adapted to this contract's
// failure modes. Fails closed (process.exit(1), naming the offending value) on any of:
//   1. missing results file
//   2. malformed JSON
//   3. schema mismatch (missing required top-level fields, `combinations` not an array)
//   4. zero combinations
//   5. combination count below a plausibility floor
//   6. `matrix/matrix.config.mjs` missing/unloadable (needed for the ID cross-check below)
//   7. the set of combination IDs in the results file doesn't exactly match the set of IDs in
//      matrix.config.mjs (missing and/or extra)
//   8. stale — `generatedAt` older than STALE_DAYS
//   9. not a full run — `subset !== "full"`
//  10. any combination missing a required field
//
// A missing or malformed results file must NEVER publish an empty or hand-stale table — that is
// the entire point of DEVP-70 Story 4 AC2. See ai-context/designs/peer-dependency-matrix.md §6.1,
// §8 (verbatim results-file schema).
//
// Modes:
//   node generate-peer-matrix-reference.mjs           write mode — updates .generated/*.json and
//                                                      injects/replaces the marker block in each README.
//   node generate-peer-matrix-reference.mjs --check    check mode — no writes; exits 1 with a diff
//                                                      if any target file is out of date.
//
// Path overrides (test-only — production always uses matrix/matrix-results.json and
// matrix/matrix.config.mjs relative to the repo root; these env vars exist so this generator is
// testable against a fixture without the DEVP-80 producer's `matrix/` directory having landed yet):
//   PEER_MATRIX_RESULTS_PATH, PEER_MATRIX_CONFIG_PATH

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const repoRoot = join(webRoot, "..", "..");

const resultsPath = process.env.PEER_MATRIX_RESULTS_PATH
  ? resolveMaybeRelative(process.env.PEER_MATRIX_RESULTS_PATH)
  : join(repoRoot, "matrix", "matrix-results.json");
const configPath = process.env.PEER_MATRIX_CONFIG_PATH
  ? resolveMaybeRelative(process.env.PEER_MATRIX_CONFIG_PATH)
  : join(repoRoot, "matrix", "matrix.config.mjs");

const outDir = join(webRoot, ".generated");
const outFile = join(outDir, "peer-matrix-reference.json");

const README_TARGETS = [
  { path: join(repoRoot, "README.md"), kind: "root" },
  { path: join(repoRoot, "sdk", "react", "README.md"), kind: "package" },
  { path: join(repoRoot, "sdk", "nextjs", "README.md"), kind: "package" },
];

/** `generatedAt` older than this many days is treated as "the workflow stopped running." */
const STALE_DAYS = 45;
/** Plausibility floor — see the module doc comment above. */
const MIN_PLAUSIBLE_COMBINATIONS = 1;

const REQUIRED_TOP_LEVEL_FIELDS = [
  "schemaVersion",
  "generatedAt",
  "subset",
  "combinations",
  "summary",
];
const REQUIRED_COMBINATION_FIELDS = [
  "id",
  "role",
  "label",
  "packagesUnderTest",
  "requested",
  "resolved",
  "node",
  "packageManager",
  "moduleResolution",
  "outcome",
  "steps",
];
const REQUIRED_VERSION_FIELDS = ["next", "react", "reactDom"];
const REQUIRED_STEP_FIELDS = [
  "install",
  "typePackageCheck",
  "typecheck",
  "build",
  "ssrRender",
  "jsdomBehaviour",
];

const MARKER_START =
  "<!-- PEER-MATRIX:START — generated by apps/web/scripts/generate-peer-matrix-reference.mjs from\n" +
  "     matrix/matrix-results.json. Do not hand-edit between these markers; run\n" +
  "     `pnpm generate:peer-matrix-readme` instead. -->";
const MARKER_END = "<!-- PEER-MATRIX:END -->";

const CHECK_MODE = process.argv.includes("--check");

function resolveMaybeRelative(p) {
  return p.startsWith("/") ? p : join(process.cwd(), p);
}

function fail(message) {
  console.error(`[generate-peer-matrix-reference] ${message}`);
  process.exit(1);
  // Unreachable, but keeps callers from needing to `return` after `fail(...)`.
  throw new Error(message);
}

function relRepo(p) {
  return relative(repoRoot, p);
}

// ---------------------------------------------------------------------------
// 1. Load + validate matrix-results.json
// ---------------------------------------------------------------------------

function loadResults() {
  if (!existsSync(resultsPath)) {
    fail(
      `no results file found at ${relRepo(resultsPath)} — run the peer-matrix workflow before ` +
        `publishing; refusing to publish an empty or fabricated table.`,
    );
  }

  const raw = readFileSync(resultsPath, "utf-8");

  let data;
  try {
    data = JSON.parse(raw);
  } catch (err) {
    fail(`${relRepo(resultsPath)} is not valid JSON — ${err.message}. Refusing to publish.`);
  }

  // Fail-closed check 3: schema mismatch.
  const missingTopLevel = REQUIRED_TOP_LEVEL_FIELDS.filter((f) => !(f in data));
  if (missingTopLevel.length > 0) {
    fail(
      `${relRepo(resultsPath)} is missing required top-level field(s): ${missingTopLevel.join(", ")}. ` +
        `This does not match the documented schema (peer-dependency-matrix.md §8) — refusing to publish.`,
    );
  }
  if (!Array.isArray(data.combinations)) {
    fail(
      `${relRepo(resultsPath)}'s "combinations" field is not an array (got ${typeof data.combinations}) — ` +
        `schema mismatch, refusing to publish.`,
    );
  }

  // Fail-closed check 4: zero combinations.
  if (data.combinations.length === 0) {
    fail(`${relRepo(resultsPath)} has zero combinations — refusing to publish an empty table.`);
  }

  // Fail-closed check 5: plausibility floor.
  if (data.combinations.length < MIN_PLAUSIBLE_COMBINATIONS) {
    fail(
      `${relRepo(resultsPath)} has ${data.combinations.length} combination(s), below the ` +
        `plausibility floor of ${MIN_PLAUSIBLE_COMBINATIONS} — generation "succeeded" but found ` +
        `(almost) nothing, which is itself the bug. Refusing to publish.`,
    );
  }

  return data;
}

// ---------------------------------------------------------------------------
// 2. Load matrix.config.mjs — only to know which combination IDs should exist
// ---------------------------------------------------------------------------

async function loadConfigCombinationIds() {
  if (!existsSync(configPath)) {
    fail(
      `could not find ${relRepo(configPath)} — needed to verify the results file covers every ` +
        `configured combination (and none stale/extra). Refusing to publish without it.`,
    );
  }
  let mod;
  try {
    mod = await import(pathToFileURL(configPath).href);
  } catch (err) {
    fail(`failed to load ${relRepo(configPath)} — ${err.message}. Refusing to publish.`);
  }
  if (!Array.isArray(mod.combinations) || mod.combinations.length === 0) {
    fail(
      `${relRepo(configPath)} exported no combinations (or a non-array "combinations") — cannot ` +
        `verify the results file's completeness. Refusing to publish.`,
    );
  }
  return new Set(mod.combinations.map((c) => c.id));
}

// ---------------------------------------------------------------------------
// 3. Cross-check IDs, staleness, subset, per-combination required fields
// ---------------------------------------------------------------------------

function crossCheckIds(data, configIds) {
  const resultIds = new Set(data.combinations.map((c) => c.id));
  const missing = [...configIds].filter((id) => !resultIds.has(id));
  const extra = [...resultIds].filter((id) => !configIds.has(id));
  if (missing.length > 0 || extra.length > 0) {
    fail(
      `${relRepo(resultsPath)}'s combination IDs don't match ${relRepo(configPath)}'s — ` +
        `missing: [${missing.join(", ") || "none"}], extra: [${extra.join(", ") || "none"}]. ` +
        `Refusing to publish an incomplete or stale table.`,
    );
  }
}

function checkStaleness(data) {
  const generatedAt = new Date(data.generatedAt);
  if (Number.isNaN(generatedAt.getTime())) {
    fail(`${relRepo(resultsPath)}'s "generatedAt" (${data.generatedAt}) is not a valid date.`);
  }
  const ageDays = (Date.now() - generatedAt.getTime()) / (24 * 60 * 60 * 1000);
  if (ageDays > STALE_DAYS) {
    fail(
      `${relRepo(resultsPath)} is ${ageDays.toFixed(1)} days old (threshold: ${STALE_DAYS} days) — ` +
        `the peer-matrix workflow appears to have stopped running; refusing to publish a stale table.`,
    );
  }
}

function checkSubset(data) {
  if (data.subset !== "full") {
    fail(
      `${relRepo(resultsPath)}'s "subset" is "${data.subset}", expected "full" — the committed ` +
        `results file must only ever be a full-run output; refusing to publish a partial table as ` +
        `if it were complete.`,
    );
  }
}

function checkCombinationFields(data) {
  for (const combo of data.combinations) {
    const id = combo?.id ?? "<missing id>";
    const missingFields = REQUIRED_COMBINATION_FIELDS.filter((f) => !(f in (combo ?? {})));
    if (missingFields.length > 0) {
      fail(`combination "${id}" is missing required field(s): ${missingFields.join(", ")}.`);
    }
    for (const versionField of ["requested", "resolved"]) {
      const missingVersions = REQUIRED_VERSION_FIELDS.filter(
        (f) => !(f in (combo[versionField] ?? {})),
      );
      if (missingVersions.length > 0) {
        fail(
          `combination "${id}"'s "${versionField}" is missing field(s): ${missingVersions.join(", ")}.`,
        );
      }
    }
    const missingSteps = REQUIRED_STEP_FIELDS.filter(
      (f) => !("outcome" in (combo.steps?.[f] ?? {})),
    );
    if (missingSteps.length > 0) {
      fail(`combination "${id}"'s "steps" is missing outcome(s) for: ${missingSteps.join(", ")}.`);
    }
  }
}

// ---------------------------------------------------------------------------
// 4. Render
// ---------------------------------------------------------------------------

function buildTypecheckOutcome(combo) {
  const gate = ["install", "typePackageCheck", "typecheck", "build"];
  return gate.every((step) => combo.steps[step].outcome === "pass") ? "pass" : "fail";
}

function buildRows(data) {
  return data.combinations.map((combo) => {
    const floorSuffix = combo.role === "floor" ? " (declared floor)" : "";
    return {
      id: combo.id,
      next: `${combo.resolved.next}${floorSuffix}`,
      react: `${combo.resolved.react}${floorSuffix}`,
      reactDom: combo.resolved.reactDom,
      verifiedDate: data.generatedAt.slice(0, 10),
      buildTypecheck: buildTypecheckOutcome(combo),
      ssr: combo.steps.ssrRender.outcome,
      behaviour: combo.steps.jsdomBehaviour.outcome,
    };
  });
}

/** Relative link from `fromFile` to the `sdk/test` package README, POSIX-separated for markdown. */
function testPackageLink(fromFile) {
  const rel = relative(dirname(fromFile), join(repoRoot, "sdk", "test"))
    .split("\\")
    .join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

function renderMarkerBlock({ rows, coverageLimits, fromFile }) {
  const header =
    "| Next.js | React | React DOM | Verified | Build + typecheck | SSR (HTML + cookie value) | Behaviour (jsdom) |\n" +
    "|---|---|---|---|---|---|---|";
  const body = rows
    .map(
      (r) =>
        `| ${r.next} | ${r.react} | ${r.reactDom} | ${r.verifiedDate} | ${r.buildTypecheck} | ${r.ssr} | ${r.behaviour} |`,
    )
    .join("\n");

  const testLink = testPackageLink(fromFile);
  const rationaleLink = "https://github.com/cookieyes/cookieyes#compatibility";

  // Static claims this generator itself makes (things the verification depth structurally never
  // covers, independent of any one matrix run) plus, dynamically, every limit the *producer*
  // reported for this specific run (`coverageLimits`, §8) — so "no real browser paint/hydration"
  // and "node dimension not varied" are sourced from the results file itself, not duplicated by
  // hand here and left to drift out of sync with it.
  const notVerifiedItems = [
    "Any Next.js/React version outside the rows above.",
    "npm/yarn as the install client.",
    ...coverageLimits,
  ];

  return [
    MARKER_START,
    header,
    body,
    "",
    `Verified by installing the exact versions above, building a real Next.js app, server-rendering ` +
      `it and asserting the banner's HTML (and a returning visitor's cookie value) is correct, then ` +
      `running behaviour assertions in \`jsdom\` via [\`@cookieyes/test\`](${testLink}). Node 20, pnpm. ` +
      `See [rationale](${rationaleLink}) for why this stops short of a real browser.`,
    "",
    "**Not verified by this table:**",
    ...notVerifiedItems.map((item) => `- ${item}`),
    MARKER_END,
  ].join("\n");
}

function injectIntoContent(content, block, kind) {
  const startIdx = content.indexOf("<!-- PEER-MATRIX:START");
  const endMarkerLiteral = "<!-- PEER-MATRIX:END -->";
  if (startIdx !== -1) {
    const endIdx = content.indexOf(endMarkerLiteral, startIdx);
    if (endIdx === -1) {
      fail(`found "PEER-MATRIX:START" without a matching "PEER-MATRIX:END" — file is malformed.`);
    }
    return content.slice(0, startIdx) + block + content.slice(endIdx + endMarkerLiteral.length);
  }

  // No existing marker block — insert fresh, right before "## Quick start".
  const anchor = "\n## Quick start";
  const anchorIdx = content.indexOf(anchor);
  if (anchorIdx === -1) {
    fail(`could not find the "## Quick start" anchor heading to insert the compatibility table.`);
  }
  const inserted = kind === "root" ? `\n## Compatibility\n\n${block}\n` : `\n${block}\n`;
  return content.slice(0, anchorIdx) + inserted + content.slice(anchorIdx);
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

async function main() {
  const data = loadResults();
  const configIds = await loadConfigCombinationIds();

  crossCheckIds(data, configIds);
  checkStaleness(data);
  checkSubset(data);
  checkCombinationFields(data);

  const rows = buildRows(data);
  const coverageLimits = Array.isArray(data.coverageLimits) ? data.coverageLimits : [];

  const referenceData = {
    generatedAt: data.generatedAt,
    commit: data.commit ?? null,
    subset: data.subset,
    rows,
    coverageLimits,
  };

  let outOfDate = false;

  for (const target of README_TARGETS) {
    const existing = readFileSync(target.path, "utf-8");
    const block = renderMarkerBlock({ rows, coverageLimits, fromFile: target.path });
    const updated = injectIntoContent(existing, block, target.kind);

    if (updated === existing) continue;

    if (CHECK_MODE) {
      outOfDate = true;
      console.error(
        `[generate-peer-matrix-reference] ${relRepo(target.path)} is out of date — run ` +
          `\`pnpm generate:peer-matrix-readme\` to update it.`,
      );
      continue;
    }

    writeFileSync(target.path, updated);
    console.log(`[generate-peer-matrix-reference] updated ${relRepo(target.path)}`);
  }

  if (CHECK_MODE) {
    if (outOfDate) {
      fail(
        `one or more README files are out of date relative to ${relRepo(resultsPath)}. Run ` +
          `\`pnpm generate:peer-matrix-readme\` and commit the result.`,
      );
    }
    console.log(
      `[generate-peer-matrix-reference] all ${README_TARGETS.length} README target(s) are up to date.`,
    );
    return;
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, `${JSON.stringify(referenceData, null, 2)}\n`);

  console.log(
    `[generate-peer-matrix-reference] wrote ${rows.length} combination(s) to ` +
      `${relRepo(outFile)} and injected the compatibility table into ${README_TARGETS.length} README(s).`,
  );
}

await main();
